//! Embedded single-page web UI.
//!
//! The dashboard is three static files compiled into the daemon with
//! [`include_str!`] (`index.html`, `app.js`, `styles.css`) plus a generated
//! `/config.js` that tells the browser where the Sandbox API lives. The edge
//! mounts [`router`] on the root host (`<base>`), so the UI is reachable at
//! `http://warren.localhost:7337/` in the default configuration.
//!
//! The UI itself is vanilla JavaScript with no build step and no external
//! resources: everything the browser needs is served from this crate. Every
//! call it makes goes to `window.WARREN.apiUrl` (the Sandbox API) with an
//! `Authorization: Bearer` header, or to an instance URL with `X-Warren-Key`.

use std::fmt::Write as _;

use axum::{
    Router,
    body::Bytes,
    http::{StatusCode, header},
    response::{IntoResponse, Response},
    routing::get,
};
use warren_core::Config;

/// `static/index.html`, embedded at compile time.
pub const INDEX_HTML: &str = include_str!("../static/index.html");
/// `static/app.js`, embedded at compile time.
pub const APP_JS: &str = include_str!("../static/app.js");
/// `static/styles.css`, embedded at compile time.
pub const STYLES_CSS: &str = include_str!("../static/styles.css");

/// Content type of HTML responses.
pub const CONTENT_TYPE_HTML: &str = "text/html; charset=utf-8";
/// Content type of JavaScript responses (RFC 9239).
pub const CONTENT_TYPE_JS: &str = "text/javascript; charset=utf-8";
/// Content type of CSS responses.
pub const CONTENT_TYPE_CSS: &str = "text/css; charset=utf-8";
/// Content type of plain-text responses.
pub const CONTENT_TYPE_TEXT: &str = "text/plain; charset=utf-8";

/// `Cache-Control` value on every dashboard response: browsers may keep a
/// copy but must revalidate, so a daemon upgrade is picked up on reload.
const NO_CACHE: &str = "no-cache";

/// Build the dashboard router.
///
/// Routes:
/// - `GET /` and `GET /index.html` -> the page (`text/html`)
/// - `GET /app.js` -> the application script (`text/javascript`)
/// - `GET /styles.css` -> the stylesheet (`text/css`)
/// - `GET /config.js` -> [`config_script`] for this configuration
/// - `GET /healthz` -> `ok`
///
/// Everything else is `404 Not Found` in plain text. All responses carry
/// `Cache-Control: no-cache` and `X-Content-Type-Options: nosniff`.
pub fn router(cfg: &Config) -> Router {
    let config_js = Bytes::from(config_script(cfg));
    Router::new()
        .route("/", get(index))
        .route("/index.html", get(index))
        .route("/app.js", get(app_js))
        .route("/styles.css", get(styles_css))
        .route(
            "/config.js",
            get(move || {
                let body = config_js.clone();
                async move { asset(CONTENT_TYPE_JS, body) }
            }),
        )
        .route("/healthz", get(healthz))
        .fallback(not_found)
}

/// The JavaScript served as `/config.js`.
///
/// It defines a frozen `window.WARREN` object with `baseDomain`,
/// `publicScheme`, `publicPort` (a number), `apiUrl` (the public Sandbox API
/// base, e.g. `http://api.warren.localhost:7337/v1`) and `version`. Strings
/// are escaped as JavaScript string literals, with `<`, `>` and `&` written as
/// `\u` escapes so the output can never close a `<script>` element.
pub fn config_script(cfg: &Config) -> String {
    let mut out = String::with_capacity(256);
    out.push_str("// Generated by warrend from its configuration; do not edit.\n");
    out.push_str("window.WARREN = Object.freeze({\n");
    let _ = writeln!(out, "  baseDomain: {},", js_string(&cfg.base_domain));
    let _ = writeln!(out, "  publicScheme: {},", js_string(&cfg.public_scheme));
    let _ = writeln!(out, "  publicPort: {},", cfg.public_port);
    let _ = writeln!(out, "  apiUrl: {},", js_string(&cfg.api_url()));
    let _ = writeln!(out, "  version: {}", js_string(&cfg.version));
    out.push_str("});\n");
    out
}

/// Render `s` as a double-quoted JavaScript string literal.
///
/// Quotes, backslashes and control characters are escaped; `<`, `>`, `&` and
/// the line separators U+2028/U+2029 become `\uXXXX` escapes so the literal is
/// safe inside an inline or external script regardless of its content.
fn js_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '<' | '>' | '&' | '\u{2028}' | '\u{2029}' => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c if c.is_control() => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// A `200 OK` with the given content type, `Cache-Control: no-cache` and
/// `X-Content-Type-Options: nosniff`.
fn asset(content_type: &'static str, body: impl Into<Bytes>) -> Response {
    (
        [
            (header::CONTENT_TYPE, content_type),
            (header::CACHE_CONTROL, NO_CACHE),
            (header::X_CONTENT_TYPE_OPTIONS, "nosniff"),
        ],
        body.into(),
    )
        .into_response()
}

async fn index() -> Response {
    asset(CONTENT_TYPE_HTML, INDEX_HTML)
}

async fn app_js() -> Response {
    asset(CONTENT_TYPE_JS, APP_JS)
}

async fn styles_css() -> Response {
    asset(CONTENT_TYPE_CSS, STYLES_CSS)
}

async fn healthz() -> Response {
    asset(CONTENT_TYPE_TEXT, "ok")
}

async fn not_found() -> Response {
    (
        StatusCode::NOT_FOUND,
        [
            (header::CONTENT_TYPE, CONTENT_TYPE_TEXT),
            (header::CACHE_CONTROL, NO_CACHE),
        ],
        "not found\n",
    )
        .into_response()
}

#[cfg(test)]
mod tests {
    use std::{
        future::Future,
        pin::pin,
        task::{Context, Poll, Waker},
    };

    use axum::{
        body::{Body, to_bytes},
        handler::Handler,
        http::{Method, Request},
        routing::any_service,
    };

    use super::*;

    /// Poll a future to completion on the current thread. The dashboard never
    /// waits on I/O, so a no-op waker and a bounded spin are enough; this keeps
    /// the crate free of an async runtime dependency.
    fn block_on<F: Future>(fut: F) -> F::Output {
        let mut fut = pin!(fut);
        let mut cx = Context::from_waker(Waker::noop());
        for _ in 0..100_000 {
            if let Poll::Ready(v) = fut.as_mut().poll(&mut cx) {
                return v;
            }
            std::thread::yield_now();
        }
        panic!("future did not complete");
    }

    /// Send one request through the full router (routing, method matching,
    /// fallback) and return the response.
    fn send(cfg: &Config, method: Method, path: &str) -> Response {
        let req = Request::builder()
            .method(method)
            .uri(path)
            .body(Body::empty())
            .expect("request");
        // `any_service` wraps the router in a `MethodRouter`, which implements
        // `Handler`; that is the public entry point we can drive without `tower`.
        block_on(Handler::call(any_service(router(cfg)), req, ()))
    }

    fn get(cfg: &Config, path: &str) -> (StatusCode, http::HeaderMap, String) {
        let resp = send(cfg, Method::GET, path);
        let (parts, body) = resp.into_parts();
        let bytes = block_on(to_bytes(body, usize::MAX)).expect("body");
        (
            parts.status,
            parts.headers,
            String::from_utf8(bytes.to_vec()).expect("utf-8 body"),
        )
    }

    fn header<'a>(h: &'a http::HeaderMap, name: &str) -> &'a str {
        h.get(name)
            .and_then(|v| v.to_str().ok())
            .unwrap_or_default()
    }

    #[test]
    fn serves_index_at_root() {
        let cfg = Config::default();
        for path in ["/", "/index.html"] {
            let (status, headers, body) = get(&cfg, path);
            assert_eq!(status, StatusCode::OK, "{path}");
            assert_eq!(header(&headers, "content-type"), CONTENT_TYPE_HTML);
            assert_eq!(header(&headers, "cache-control"), "no-cache");
            assert_eq!(header(&headers, "x-content-type-options"), "nosniff");
            assert_eq!(body, INDEX_HTML);
        }
        assert!(
            INDEX_HTML.starts_with("<!doctype html>"),
            "index.html must start with a doctype"
        );
    }

    #[test]
    fn serves_app_js() {
        let (status, headers, body) = get(&Config::default(), "/app.js");
        assert_eq!(status, StatusCode::OK);
        assert_eq!(header(&headers, "content-type"), CONTENT_TYPE_JS);
        assert_eq!(header(&headers, "cache-control"), "no-cache");
        assert_eq!(body, APP_JS);
    }

    #[test]
    fn serves_styles_css() {
        let (status, headers, body) = get(&Config::default(), "/styles.css");
        assert_eq!(status, StatusCode::OK);
        assert_eq!(header(&headers, "content-type"), CONTENT_TYPE_CSS);
        assert_eq!(header(&headers, "cache-control"), "no-cache");
        assert_eq!(body, STYLES_CSS);
    }

    #[test]
    fn config_script_carries_the_configuration() {
        let cfg = Config {
            base_domain: "sandbox.example.com".into(),
            public_scheme: "https".into(),
            public_port: 443,
            version: "1.2.3".into(),
            ..Config::default()
        };
        let (status, headers, body) = get(&cfg, "/config.js");
        assert_eq!(status, StatusCode::OK);
        assert_eq!(header(&headers, "content-type"), CONTENT_TYPE_JS);
        assert_eq!(header(&headers, "cache-control"), "no-cache");
        assert_eq!(body, config_script(&cfg));
        assert!(body.starts_with("// Generated"), "{body}");
        assert!(body.contains("window.WARREN = Object.freeze({"), "{body}");
        assert!(
            body.contains("baseDomain: \"sandbox.example.com\""),
            "{body}"
        );
        assert!(body.contains("publicScheme: \"https\""), "{body}");
        assert!(body.contains("publicPort: 443"), "{body}");
        assert!(
            body.contains("apiUrl: \"https://api.sandbox.example.com/v1\""),
            "{body}"
        );
        assert!(body.contains("version: \"1.2.3\""), "{body}");
    }

    #[test]
    fn config_script_default_has_port_in_api_url() {
        let body = config_script(&Config::default());
        assert!(body.contains("baseDomain: \"warren.localhost\""), "{body}");
        assert!(body.contains("publicPort: 7337"), "{body}");
        assert!(
            body.contains("apiUrl: \"http://api.warren.localhost:7337/v1\""),
            "{body}"
        );
    }

    #[test]
    fn config_script_escapes_hostile_values() {
        let cfg = Config {
            base_domain: "</script><script>alert(\"x\")\\\n".into(),
            version: "tab\tand\u{2028}sep\u{1}".into(),
            ..Config::default()
        };
        let body = config_script(&cfg);
        assert!(!body.contains("</script>"), "{body}");
        assert!(!body.contains('\u{2028}'), "{body}");
        assert!(
            body.contains(r#"\u003c/script\u003e\u003cscript\u003ealert(\"x\")\\\n"#),
            "{body}"
        );
        assert!(body.contains(r"tab\tand\u2028sep\u0001"), "{body}");
        assert_eq!(js_string("plain"), "\"plain\"");
        assert_eq!(js_string("a&b"), "\"a\\u0026b\"");
    }

    #[test]
    fn healthz_says_ok() {
        let (status, headers, body) = get(&Config::default(), "/healthz");
        assert_eq!(status, StatusCode::OK);
        assert_eq!(header(&headers, "content-type"), CONTENT_TYPE_TEXT);
        assert_eq!(body, "ok");
    }

    #[test]
    fn unknown_paths_are_404_and_other_methods_405() {
        let cfg = Config::default();
        let (status, headers, body) = get(&cfg, "/nope.txt");
        assert_eq!(status, StatusCode::NOT_FOUND);
        assert_eq!(header(&headers, "content-type"), CONTENT_TYPE_TEXT);
        assert_eq!(body, "not found\n");
        let (status, _, _) = get(&cfg, "/v1/instances");
        assert_eq!(
            status,
            StatusCode::NOT_FOUND,
            "the edge routes /v1 to the API; the dashboard must not claim it"
        );
        let resp = send(&cfg, Method::POST, "/");
        assert_eq!(resp.status(), StatusCode::METHOD_NOT_ALLOWED);
        let resp = send(&cfg, Method::DELETE, "/app.js");
        assert_eq!(resp.status(), StatusCode::METHOD_NOT_ALLOWED);
    }

    #[test]
    fn page_references_only_embedded_resources() {
        assert!(
            INDEX_HTML.contains("<script src=\"/config.js\"></script>"),
            "config.js must load before app.js"
        );
        assert!(INDEX_HTML.contains("src=\"/app.js\""));
        assert!(INDEX_HTML.contains("href=\"/styles.css\""));
        assert!(INDEX_HTML.contains("<html lang=\"en\">"));
        let config_pos = INDEX_HTML.find("/config.js").unwrap();
        let app_pos = INDEX_HTML.find("/app.js").unwrap();
        assert!(
            config_pos < app_pos,
            "config.js must be included before app.js"
        );
        for text in [INDEX_HTML, APP_JS, STYLES_CSS] {
            for needle in [
                "https://",
                "http://cdn",
                "//cdn.",
                "@import url(",
                "unpkg",
                "jsdelivr",
                "googleapis",
            ] {
                assert!(
                    !text.contains(needle),
                    "external resource reference `{needle}` found in embedded asset"
                );
            }
        }
        assert!(
            APP_JS.contains("window.WARREN"),
            "app.js must read window.WARREN"
        );
        assert!(
            APP_JS.contains("Authorization"),
            "app.js must send bearer auth"
        );
        assert!(
            APP_JS.contains("X-Warren-Key"),
            "app.js must send X-Warren-Key to instances"
        );
        assert!(
            APP_JS.contains("response.output_text.delta"),
            "app.js must render streaming deltas"
        );
        assert!(
            STYLES_CSS.contains("prefers-color-scheme: dark"),
            "styles must have a dark scheme"
        );
    }

    /// Every element id the script looks up with `el('...')` must exist in the
    /// page, so a typo on either side fails the build's tests.
    #[test]
    fn script_element_ids_exist_in_page() {
        let mut missing = Vec::new();
        let mut checked = 0;
        for (i, _) in APP_JS.match_indices("el('") {
            // `showPanel('empty')` also ends in `el('`; only count the `el` helper.
            if i > 0 && APP_JS.as_bytes()[i - 1].is_ascii_alphanumeric() {
                continue;
            }
            let rest = &APP_JS[i + 4..];
            let Some(end) = rest.find('\'') else { continue };
            let id = &rest[..end];
            if id.is_empty() || id.contains(['+', ' ', '$']) {
                continue; // a computed id, not a literal
            }
            checked += 1;
            if !INDEX_HTML.contains(&format!("id=\"{id}\"")) {
                missing.push(id.to_string());
            }
        }
        assert!(
            checked > 20,
            "expected the script to look up many elements by id, found {checked}"
        );
        assert!(
            missing.is_empty(),
            "ids used by app.js but absent from index.html: {missing:?}"
        );
    }

    /// Warren is self-hosted: no billing concept may survive in the served
    /// assets.
    #[test]
    fn assets_carry_no_billing_concepts() {
        for (name, text) in [
            ("index.html", INDEX_HTML),
            ("app.js", APP_JS),
            ("styles.css", STYLES_CSS),
        ] {
            let lower = text.to_ascii_lowercase();
            for needle in [
                "billing", "wallet", "ledger", "top-up", "topup", "top_up", "credit", "price",
                "budget", "micros",
            ] {
                assert!(!lower.contains(needle), "{name} still mentions `{needle}`");
            }
        }
    }

    /// The reverse: every `for=` on a label points at a real control.
    #[test]
    fn labels_point_at_controls() {
        let mut missing = Vec::new();
        for (i, _) in INDEX_HTML.match_indices("for=\"") {
            let rest = &INDEX_HTML[i + 5..];
            let Some(end) = rest.find('"') else { continue };
            let id = &rest[..end];
            if !INDEX_HTML.contains(&format!("id=\"{id}\"")) {
                missing.push(id.to_string());
            }
        }
        assert!(missing.is_empty(), "labels without a control: {missing:?}");
    }
}
